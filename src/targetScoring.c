static UBYTE GetScoreFromMap(const UBYTE *map, UWORD width, WORD x, WORD y) {
    return map[y * width + x];
}

UBYTE TargetScoring_GetScore(UWORD distance, WORD localX, WORD localY) {
    switch (distance) {
        case 300:
            return GetScoreFromMap((const UBYTE *)gScoreMap300, 5, localX, localY);

        case 250:
            return GetScoreFromMap((const UBYTE *)gScoreMap250, 7, localX, localY);

        case 200:
            return GetScoreFromMap((const UBYTE *)gScoreMap200, 8, localX, localY);

        case 150:
            return GetScoreFromMap((const UBYTE *)gScoreMap150, 9, localX, localY);

        case 100:
            return GetScoreFromMap((const UBYTE *)gScoreMap100, 24, localX, localY);

        case 50:
            return GetScoreFromMap((const UBYTE *)gScoreMap050, 48, localX, localY);

        default:
            break;
    }

    return SCORE_MISS;
}
